#!/usr/bin/env python3
"""Tabulate the Dai et al. (2006) Ag-W EFS form as a LAMMPS eam/fs setfl file."""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path

import numpy as np
from ase.data import atomic_masses, atomic_numbers


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PARAMETERS = ROOT / "parameters" / "Dai_2006_EFS_AgW_parameters.json"
DEFAULT_OUTPUT = ROOT / "potential_files" / "derived" / "Dai_2006_EFS_AgW.eam.fs"
ELEMENTS = ("Ag", "W")
LATTICE = {"Ag": (4.09, "FCC"), "W": (3.16, "BCC")}


def pair_key(first: str, second: str) -> str:
    if first == second:
        return first
    return f"{first}_{second}" if (first, second) == ELEMENTS else f"{second}_{first}"


def pair_parameters(parameters: dict, first: str, second: str) -> dict:
    if first == second:
        return parameters["pure_element_parameters"][first]
    return parameters["cross_parameters"][pair_key(first, second)]


def density_function(radius: np.ndarray, p: dict) -> np.ndarray:
    distance = np.maximum(p["d_A"] - radius, 0.0)
    return p["A"] ** 2 * distance**2 * (1.0 + p["B"] ** 2 * distance**2)


def pair_function(radius: np.ndarray, p: dict) -> np.ndarray:
    distance = np.maximum(p["c_A"] - radius, 0.0)
    polynomial = sum(p[f"c{power}"] * radius**power for power in range(5))
    return distance**2 * polynomial


def render_file(parameters: dict, nrho: int, rho_max: float, dr: float) -> str:
    if nrho < 3 or rho_max <= 0.0 or dr <= 0.0:
        raise ValueError("nrho, rho_max, and dr must define positive interpolation grids")

    cutoff = max(
        p["c_A"]
        for first in ELEMENTS
        for second in ELEMENTS
        for p in (pair_parameters(parameters, first, second),)
    )
    nr = int(math.ceil(cutoff / dr)) + 1
    cutoff = (nr - 1) * dr
    r = np.arange(nr, dtype=float) * dr
    rho = np.linspace(0.0, rho_max, nrho)

    lines = [
        "Dai et al. (2006) Ag-W EFS tabulated as LAMMPS Finnis-Sinclair EAM",
        "DOI: 10.1088/0953-8984/18/19/008; generated by convert_dai_efs_to_eamfs.py",
        "EFS mapping: F(rho)=-sqrt(rho), rho_alpha,beta=A_alpha,beta^2*phi_alpha,beta(r), V=pair polynomial",
        f"{len(ELEMENTS)} {' '.join(ELEMENTS)}",
        f"{nrho} {rho_max / (nrho - 1):.16e} {nr} {dr:.16e} {cutoff:.16e}",
    ]

    for element in ELEMENTS:
        lattice_constant, lattice_type = LATTICE[element]
        lines.append(
            f"{atomic_numbers[element]} {atomic_masses[atomic_numbers[element]]:.12g} "
            f"{lattice_constant:.12g} {lattice_type}"
        )
        embedding = -np.sqrt(rho)
        lines.append("\n".join(
            " ".join(f"{value:.16e}" for value in embedding[start : start + 5])
            for start in range(0, nrho, 5)
        ))
        for center in ELEMENTS:
            p = pair_parameters(parameters, center, element)
            lines.append("\n".join(
                " ".join(f"{value:.16e}" for value in density_function(r[start : start + 5], p))
                for start in range(0, nr, 5)
            ))

    for first_index, first in enumerate(ELEMENTS):
        for second in ELEMENTS[: first_index + 1]:
            p = pair_parameters(parameters, first, second)
            lines.append("\n".join(
                " ".join(f"{value:.16e}" for value in (r[start : start + 5] * pair_function(r[start : start + 5], p)))
                for start in range(0, nr, 5)
            ))

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parameters", type=Path, default=DEFAULT_PARAMETERS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--nrho", type=int, default=100_001)
    parser.add_argument("--rho-max", type=float, default=1000.0)
    parser.add_argument("--dr", type=float, default=0.001)
    parser.add_argument("--force", action="store_true", help="replace the generated output files")
    args = parser.parse_args()

    parameter_bytes = args.parameters.read_bytes()
    parameters = json.loads(parameter_bytes)
    if parameters["parameter_units"]["A"] != "eV Angstrom^-1":
        raise ValueError("The Dai EFS A unit must match the primary source: eV Angstrom^-1")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    metadata_path = args.output.with_suffix(args.output.suffix + ".json")
    if not args.force and (args.output.exists() or metadata_path.exists()):
        raise FileExistsError(f"Refusing to overwrite {args.output}")

    payload = render_file(parameters, args.nrho, args.rho_max, args.dr).encode()
    args.output.write_bytes(payload)
    metadata = {
        "status": "GENERATED_EAMFS_TABLE_NOT_PRODUCTION_VALIDATED",
        "source_parameters": str(args.parameters.relative_to(ROOT)),
        "source_parameters_sha256": hashlib.sha256(parameter_bytes).hexdigest(),
        "potential_file": str(args.output.relative_to(ROOT)),
        "potential_file_sha256": hashlib.sha256(payload).hexdigest(),
        "elements": list(ELEMENTS),
        "mapping": {
            "embedding": "F(rho)=-sqrt(rho)",
            "density": "rho_alpha,beta(r)=A_alpha,beta^2*((r-d)^2+B^2*(r-d)^4), zero for r>d",
            "pair": "V_alpha,beta(r)=(r-c)^2*sum(k=0..4,c_k*r^k), zero for r>c",
            "directional_cross_density": "symmetric, using the single Ag-W parameter set",
            "lammps_eam_fs_density_order": "neighbor element beta sections, each listing center element alpha",
        },
        "grid": {
            "nrho": args.nrho,
            "rho_max": args.rho_max,
            "drho": args.rho_max / (args.nrho - 1),
            "nr": int(math.ceil(max(
                p["c_A"]
                for first in ELEMENTS
                for second in ELEMENTS
                for p in (pair_parameters(parameters, first, second),)
            ) / args.dr)) + 1,
            "dr": args.dr,
        },
    }
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
